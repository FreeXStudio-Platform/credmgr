/**
 * Design-token → ECharts theme adapter.
 *
 * Single source: tools/docgen/assets/tokens.json (mirrors KEEP's own
 * v2/design/tokens/keep.tokens.json — see tools/PROVENANCE.md). This module
 * never defines a color of its own — every value is read from the token
 * file, so editing KEEP's tokens and re-copying propagates here on the next
 * `npm run build:themes`.
 *
 * Reskin law (RESKINNING_AND_THEME_POLICY.md): themes may change appearance,
 * never data semantics. KEEP is achromatic by default — colour is reserved
 * for exactly three states (sig/warn/danger, `identity.principles` in the
 * token source) and is never decorative. `categoricalPalette` therefore
 * builds a lightness ramp from the achromatic ink/ground scale, not from an
 * invented hue set — the same "every state distinguishable in pure
 * greyscale" law the token source states as a hard requirement. `signal` is
 * exposed separately for presets that encode an actual sig/warn/danger
 * state (e.g. a gate-status matrix), and must never be used as a decorative
 * palette for an arbitrary category axis.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const ENGINE_ROOT = join(HERE, "..", "..");
const DOCGEN_TOKENS = join(ENGINE_ROOT, "..", "docgen", "assets", "tokens.json");
const THEMES_DIR = join(ENGINE_ROOT, "themes");

export function loadTokens() {
  return JSON.parse(readFileSync(DOCGEN_TOKENS, "utf8"));
}

/**
 * Categorical palette — a six-step achromatic lightness ramp (bone → ash →
 * mute → steel-3 → steel-2 → faint), ordered for maximum perceptual
 * separation against the native dark ground. Deliberately not a multi-hue
 * palette: KEEP reserves colour for state, never decoration, and a series
 * legend/label carries the identity a hue would otherwise be doing.
 */
export function categoricalPalette(t, mode = "dark") {
  const inks = mode === "light" ? t.inks_light : t.inks_dark;
  const grounds = mode === "light" ? t.grounds_light : t.grounds_dark;
  return [inks.bone, inks.ash, inks.mute, grounds["steel-3"], grounds["steel-2"], inks.faint];
}

/** Heatmap interpolation ramp — derived from the token file's own ground/signal scale. */
export function heatRamp(t) {
  return [t.grounds_dark["steel-2"], t.signal["sig-dim"], t.signal["sig-hi"]];
}

const FONT_BODY = 'Inter, system-ui, sans-serif'; // unquoted: quoted names break ECharts SSR SVG font attributes
const FONT_DISPLAY = 'Inter, system-ui, sans-serif';
const FONT_MONO = 'JetBrains Mono, ui-monospace, monospace';

function buildTheme(t, mode /* "dark" | "light" | "print" */) {
  const dark = mode === "dark";
  const grounds = dark ? t.grounds_dark : t.grounds_light;
  const inks = dark ? t.inks_dark : t.inks_light;
  const hairline = dark ? "rgba(234,238,245,0.10)" : "rgba(11,14,20,0.12)";
  const hairlineStrong = dark ? "rgba(234,238,245,0.18)" : "rgba(11,14,20,0.22)";

  return {
    _provenance: `Generated by adapters/echarts/theme-adapter.mjs from tools/docgen/assets/tokens.json (mirrors KEEP — v2/design/tokens/keep.tokens.json). Do not hand-edit — re-run \`npm run build:themes\`.`,
    _mode: mode,
    color: categoricalPalette(t, dark ? "dark" : "light"),
    backgroundColor: mode === "print" ? "#FFFFFF" : "transparent",
    textStyle: { fontFamily: FONT_BODY, color: inks.bone, fontSize: 12 },
    title: {
      textStyle: { fontFamily: FONT_DISPLAY, color: inks.bone, fontSize: 16, fontWeight: 600 },
      subtextStyle: { fontFamily: FONT_BODY, color: inks.ash, fontSize: 12 },
    },
    legend: {
      textStyle: { color: inks.ash, fontFamily: FONT_BODY, fontSize: 11 },
      pageTextStyle: { color: inks.ash },
    },
    tooltip: {
      backgroundColor: grounds["steel-2"],
      borderColor: hairlineStrong,
      textStyle: { color: inks.bone, fontFamily: FONT_BODY, fontSize: 12 },
    },
    grid: { borderColor: hairline },
    categoryAxis: {
      axisLine: { lineStyle: { color: hairlineStrong } },
      axisTick: { lineStyle: { color: hairlineStrong } },
      axisLabel: { color: inks.ash, fontFamily: FONT_BODY, fontSize: 11 },
      splitLine: { show: false },
    },
    valueAxis: {
      axisLine: { show: false },
      axisTick: { show: false },
      axisLabel: { color: inks.ash, fontFamily: FONT_MONO, fontSize: 10 },
      splitLine: { lineStyle: { color: hairline } },
    },
    timeAxis: {
      axisLine: { lineStyle: { color: hairlineStrong } },
      axisLabel: { color: inks.ash, fontFamily: FONT_MONO, fontSize: 10 },
      splitLine: { show: false },
    },
    logAxis: {
      axisLabel: { color: inks.ash, fontFamily: FONT_MONO, fontSize: 10 },
      splitLine: { lineStyle: { color: hairline } },
    },
    bar: { itemStyle: { borderRadius: [2, 2, 0, 0] } },
    line: { symbolSize: 5, lineStyle: { width: 2 }, smooth: false },
    pie: { label: { color: inks.ash, fontFamily: FONT_BODY, fontSize: 11 } },
    heatmap: { itemStyle: { borderColor: grounds.night, borderWidth: 1 } },
    graph: {
      lineStyle: { color: hairlineStrong },
      label: { color: inks.bone, fontFamily: FONT_BODY, fontSize: 11 },
    },
    sankey: {
      lineStyle: { color: "gradient", opacity: dark ? 0.25 : 0.35 },
      label: { color: inks.bone, fontFamily: FONT_BODY, fontSize: 11 },
    },
    // Semantic lattice — reserved, not decorative (sig/warn/danger meaning only).
    severity: { ...t.signal },
    semantic: {
      sig: t.signal.sig,
      warn: t.signal.warn,
      danger: t.signal.danger,
      inks,
      grounds,
      hairline,
      hairlineStrong,
      heatRamp: heatRamp(t),
    },
  };
}

export function buildAllThemes() {
  const t = loadTokens();
  return {
    "project-theme": buildTheme(t, "dark"), // native ground is dark, matching docgen
    "project-theme-dark": buildTheme(t, "dark"),
    "project-theme-light": buildTheme(t, "light"),
    "print-theme": buildTheme(t, "print"),
  };
}

if (process.argv.includes("--build")) {
  mkdirSync(THEMES_DIR, { recursive: true });
  const themes = buildAllThemes();
  for (const [name, theme] of Object.entries(themes)) {
    writeFileSync(join(THEMES_DIR, `${name}.json`), JSON.stringify(theme, null, 2) + "\n");
  }
  const t = loadTokens();
  writeFileSync(
    join(THEMES_DIR, "tokens.json"),
    JSON.stringify(
      { _provenance: "GENERATED copy of tools/docgen/assets/tokens.json for engine consumers. Source of truth is KEEP (v2/design/tokens/keep.tokens.json); re-run `npm run build:themes` after editing it there.", ...t },
      null,
      2,
    ) + "\n",
  );
  console.log(`themes built: ${Object.keys(themes).join(", ")} + tokens.json → ${THEMES_DIR}`);
}
