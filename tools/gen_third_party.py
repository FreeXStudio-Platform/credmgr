#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.md (repository root and v2/; the copies differ only in one link) from the lock files.

Standard library only. Run from anywhere:

    python3 tools/gen_third_party.py            # rewrite both files
    python3 tools/gen_third_party.py --check    # exit 1 if either file is out of date

What it lists
  * Rust crates: the NORMAL (non-dev, non-build) dependency closure of the shipped binaries
    -- `credmgr`, `credmgrd` (workspace under v2/) and the desktop shell (v2/apps/desktop/src-tauri),
    taken from `cargo metadata --offline`. Proc-macro crates and build-script-only crates are not
    traversed: they run at build time and are not linked into a binary. The list covers every
    target platform, so a crate that is only used on Windows or Linux appears too.
  * npm packages that ship: the production closure recorded in v2/apps/desktop/package-lock.json
    (the desktop app) and v1/package-lock.json (V1), i.e. entries the lock file does not flag `dev`.
  * Bundled fonts: every OFL-*.txt under v2/apps/desktop/third_party/fonts.

Workspace crates (ours) are not listed. The output contains no local paths and no timestamps, so
re-running it on an unchanged tree changes nothing.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

RUST_WORKSPACES = [
    # (manifest dir relative to ROOT, root package names whose closure ships)
    ("v2", ["credmgr-cli", "credmgr-brokerd"]),
    ("v2/apps/desktop/src-tauri", ["desktop"]),
]
NPM_LOCKS = [
    ("Desktop app (`v2/apps/desktop`)", "v2/apps/desktop/package-lock.json"),
    ("V1 (`v1`)", "v1/package-lock.json"),
]
FONT_DIR = "v2/apps/desktop/third_party/fonts"
FONT_NAMES = {
    "OFL-Inter.txt": "Inter",
    "OFL-InterTight.txt": "Inter Tight",
    "OFL-JetBrainsMono.txt": "JetBrains Mono",
}

HEADER = """# Third-party notices

CredMgr includes components written by others. Each one is under its own licence, listed below,
and is **not** covered by the FreexStudio Source-Available Licence in [`LICENSE`](LICENSE) or claimed
as FreexStudio's work. This file lists the third-party Rust crates that are linked into the shipped
binaries, the npm packages that ship in the desktop app and in V1, and the bundled fonts. Test,
build-only and development tools are not listed. The full text of each licence is published with the
component by its authors; see also {ack}.

This file is generated by `tools/gen_third_party.py` from the lock files and Cargo metadata. Do not
edit it by hand; re-run the script.
"""


def run_metadata(manifest_dir: str) -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--offline", "--format-version", "1"],
        cwd=ROOT / manifest_dir,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def rust_shipped(manifest_dir: str, roots: list[str]) -> list[tuple[str, str, str]]:
    meta = run_metadata(manifest_dir)
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    start = [pid for pid, p in pkgs.items() if p["name"] in roots and p.get("source") is None]
    seen: set[str] = set()
    stack = list(start)
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if not any(k.get("kind") is None for k in dep["dep_kinds"]):
                continue  # dev- or build-only edge
            child = pkgs[dep["pkg"]]
            if any("proc-macro" in t["kind"] for t in child["targets"]):
                continue  # runs at build time, not linked
            stack.append(dep["pkg"])
    rows = []
    for pid in seen:
        p = pkgs[pid]
        if p.get("source") is None:
            continue  # a workspace crate of ours
        lic = p.get("license") or ("see the crate's licence file" if p.get("license_file") else "not declared")
        rows.append((p["name"], p["version"], lic.replace("/", " OR ")))
    return rows


def npm_shipped(lock_rel: str) -> list[tuple[str, str, str]]:
    lock = json.loads((ROOT / lock_rel).read_text(encoding="utf-8"))
    rows = []
    for key, meta in lock["packages"].items():
        if not key or "node_modules/" not in key:
            continue
        if meta.get("dev"):
            continue
        name = key.rsplit("node_modules/", 1)[1]
        lic = meta.get("license")
        if isinstance(lic, dict):
            lic = lic.get("type")
        if isinstance(lic, list):
            lic = " OR ".join(str(x.get("type", x)) if isinstance(x, dict) else str(x) for x in lic)
        rows.append((name, meta.get("version", "?"), lic or "not declared"))
    return rows


def table(rows: list[tuple[str, str, str]]) -> str:
    out = ["| Name | Version | Licence |", "|---|---|---|"]
    for name, ver, lic in sorted(set(rows), key=lambda r: (r[0].lower(), r[1])):
        out.append(f"| `{name}` | {ver} | {lic} |")
    return "\n".join(out)


def build(ack: str) -> str:
    parts = [HEADER.replace("{ack}", ack)]

    rust_rows: list[tuple[str, str, str]] = []
    for manifest_dir, roots in RUST_WORKSPACES:
        rust_rows += rust_shipped(manifest_dir, roots)
    parts.append(f"## Rust crates ({len(set(rust_rows))})\n")
    parts.append(
        "Linked into `credmgr`, `credmgrd` and the desktop shell, across all supported platforms. "
        "Licence expressions are taken from each crate's published metadata.\n"
    )
    parts.append(table(rust_rows) + "\n")

    for label, lock_rel in NPM_LOCKS:
        rows = npm_shipped(lock_rel)
        parts.append(f"## npm packages: {label} ({len(set(rows))})\n")
        parts.append(table(rows) + "\n")

    fonts = []
    fdir = ROOT / FONT_DIR
    if fdir.is_dir():
        for f in sorted(fdir.glob("OFL-*.txt")):
            fonts.append(FONT_NAMES.get(f.name, f.stem.replace("OFL-", "")))
    parts.append(f"## Bundled fonts ({len(fonts)})\n")
    parts.append(
        "SIL Open Font Licence 1.1. The licence texts ship with the app under "
        "`v2/apps/desktop/third_party/fonts`.\n"
    )
    parts.append("\n".join(f"- {n}" for n in fonts) + "\n")
    return "\n".join(parts)


def main() -> int:
    # The two copies differ only in the link to the acknowledgements, which sit in v1/ and v2/.
    outputs = {
        ROOT / "THIRD_PARTY_NOTICES.md": build("[`v2/ACKNOWLEDGEMENTS.md`](v2/ACKNOWLEDGEMENTS.md) and [`v1/ACKNOWLEDGEMENTS.md`](v1/ACKNOWLEDGEMENTS.md)"),
        ROOT / "v2" / "THIRD_PARTY_NOTICES.md": build("[`ACKNOWLEDGEMENTS.md`](ACKNOWLEDGEMENTS.md)"),
    }
    if "--check" in sys.argv:
        stale = [t for t, text in outputs.items() if not t.exists() or t.read_text(encoding="utf-8") != text]
        if stale:
            print("out of date: " + ", ".join(str(t.relative_to(ROOT)) for t in stale))
            return 1
        print("up to date")
        return 0
    for t, text in outputs.items():
        t.write_text(text, encoding="utf-8")
        print(f"wrote {t.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
